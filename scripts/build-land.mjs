// Builds src/land-mask.ts: a land/sea grid of the world from Natural Earth.
//
//   node scripts/build-land.mjs path/to/ne_50m_land.geojson [cellsPerDegree]
//
// Natural Earth is public domain (https://www.naturalearthdata.com). Download
// ne_50m_land.geojson from github.com/nvkelso/natural-earth-vector (geojson/).
//
// The grid is equirectangular, row 0 at 90°N, column 0 at 180°W. Each cell is
// land if its centre falls inside a land polygon (even-odd rule).
//
// The grid is stored as an adaptive binary range coder stream (LZMA style
// carry handling), base64 encoded. Each cell is coded from the 7 cells already
// decoded around it (two to the left, three above, one above-right-right, one
// two rows up), so coasts that barely move between rows cost almost nothing.
// The model below and the decoder in src/index.ts must stay in step; verify
// with scripts/verify-land.mjs.
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"

const [, , input, perDegArg] = process.argv
if (!input) {
  console.error("usage: node scripts/build-land.mjs ne_50m_land.geojson [cellsPerDegree=2]")
  process.exit(1)
}
const PER_DEG = Number(perDegArg || 2)
const W = 360 * PER_DEG
const H = 180 * PER_DEG

const geo = JSON.parse(readFileSync(input, "utf8"))
const rings = []
for (const f of geo.features) {
  const g = f.geometry
  const polys = g.type === "Polygon" ? [g.coordinates] : g.type === "MultiPolygon" ? g.coordinates : []
  for (const poly of polys) for (const ring of poly) rings.push(ring)
}

// Edges grouped by the rows they cross, so each row only tests its own edges.
const rowEdges = Array.from({ length: H }, () => [])
for (const ring of rings) {
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [x1, y1] = ring[j]
    const [x2, y2] = ring[i]
    if (y1 === y2) continue
    const lo = Math.min(y1, y2)
    const hi = Math.max(y1, y2)
    const r0 = Math.max(0, Math.floor((90 - hi) * PER_DEG - 0.5))
    const r1 = Math.min(H - 1, Math.ceil((90 - lo) * PER_DEG - 0.5))
    for (let r = r0; r <= r1; r++) rowEdges[r].push([x1, y1, x2, y2])
  }
}

const grid = new Uint8Array(W * H)
let land = 0
for (let r = 0; r < H; r++) {
  const lat = 90 - (r + 0.5) / PER_DEG
  const xs = []
  for (const [x1, y1, x2, y2] of rowEdges[r]) {
    if ((y1 > lat) !== (y2 > lat)) xs.push(x1 + ((lat - y1) * (x2 - x1)) / (y2 - y1))
  }
  xs.sort((a, b) => a - b)
  for (let k = 0; k + 1 < xs.length; k += 2) {
    const c0 = Math.max(0, Math.ceil((xs[k] + 180) * PER_DEG - 0.5))
    const c1 = Math.min(W - 1, Math.floor((xs[k + 1] + 180) * PER_DEG - 0.5))
    for (let c = c0; c <= c1; c++) {
      grid[r * W + c] = 1
      land++
    }
  }
}

// ---- range coder (see the header comment) ----
const PAD = 2
const S = W + 2 * PAD
const OFFS = [1, 2, S + 1, S, S - 1, S - 2, 2 * S] // cells already seen, as distance behind the current one
const padded = new Uint8Array(S * (H + PAD))
const prob = new Float64Array(1 << OFFS.length).fill(0.5) // chance the next cell is land, per context
const seen = new Float64Array(1 << OFFS.length)
const out = []
let low = 0
let range = 0xffffffff
let cache = 0
let cacheSize = 1
const shiftLow = () => {
  if (low < 0xff000000 || low >= 2 ** 32) {
    const carry = low >= 2 ** 32 ? 1 : 0
    let t = cache
    do {
      out.push((t + carry) & 255)
      t = 255
    } while (--cacheSize)
    cache = Math.floor(low / 2 ** 24) & 255
  }
  cacheSize++
  low = (low % 2 ** 24) * 256
}
for (let y = 0; y < H; y++) {
  for (let x = 0; x < W; x++) {
    const j = (y + PAD) * S + x + PAD
    let c = 0
    for (const k of OFFS) c = c * 2 + padded[j - k]
    const b = grid[y * W + x]
    const q = ((1 - prob[c]) * 32766 + 1) | 0 // chance of sea, 15 bits, never 0 or 32768
    const bound = (range >>> 15) * q
    if (b) {
      low += bound
      range -= bound
    } else range = bound
    while (range < 2 ** 24) {
      range *= 256
      shiftLow()
    }
    prob[c] += (b - prob[c]) / (seen[c] + 2)
    if (seen[c] < 1000) seen[c]++
    padded[j] = b
  }
}
for (let k = 0; k < 5; k++) shiftLow()
// The first byte is always 0 and trailing zeros are implied, so neither is stored.
let end = out.length
while (end > 1 && out[end - 1] === 0) end--
const bytes = Buffer.from(out.slice(1, end))

const b64 = bytes.toString("base64")
const here = dirname(fileURLToPath(import.meta.url))
const file = join(here, "../src/land-mask.ts")
writeFileSync(
  file,
  `// Generated by scripts/build-land.mjs from Natural Earth (public domain,
// https://www.naturalearthdata.com). Do not edit by hand.
// Equirectangular land grid, ${W}x${H}, row 0 at 90°N, column 0 at 180°W.
// Adaptive binary range coder stream (see the script), base64 encoded.
export const LAND_W = ${W}
export const LAND_H = ${H}
export const LAND_DATA = "${b64}"
`,
)
console.log(`${W}x${H} grid, ${((land / grid.length) * 100).toFixed(1)}% land, ${bytes.length} bytes coded, ${b64.length} chars base64 -> ${file}`)
